const byId = new Map(PROVIDERS.map((p) => [p.id, p]))

export function providerById(id) {
  return byId.get(String(id || '')) || null
}

export function publicProviders() {
  return PROVIDERS.map(({ id, name, protocol, baseUrl, keyUrl, docs, note, tags, popular, models }) => ({
    id,
    name,
    protocol,
    baseUrl,
    keyUrl,
    docs,
    note,
    tags: [...tags],
    popular: !!popular,
    models: [...models],
  }))
}
